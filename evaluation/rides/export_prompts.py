#!/usr/bin/env python3
"""Write PROMPTS.md: every instruction sent to the agent in the ride-hailing scenario, verbatim.

Usage: python export_prompts.py  (writes evaluation/rides/PROMPTS.md)
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.argv = sys.argv[:1]

import run_rides as rr  # noqa: E402
from agentlib import build_prompt  # noqa: E402


def block(text: str) -> str:
    return "```text\n" + text.rstrip() + "\n```\n"


def main() -> int:
    parts = ["# Instructions of the ride-hailing and food delivery scenario", "",
             "Generated by `export_prompts.py` from `prompts.yaml` and `SPEC.md`. The agent also sees "
             "`INTERFACE.md` in every condition and `docs/SPEC.md` at the requirements and super levels.", ""]
    parts += ["## 1. One-line wish (direct)", "", block(rr.PROMPTS["one_line"])]
    parts += ["## 2. Paragraph (direct)", "", block(rr.PROMPTS["paragraph"])]
    parts += ["## 3. Full requirements (direct)", "", block(rr.PROMPTS["requirements_intro"])]
    parts += ["## 4. Super prompt (direct)", "", block(rr.super_text())]
    parts += ["## 5. Governed tasks", "",
              "The harness receives task files; its command adapter turns each one into the prompt below "
              "(`agentlib.build_prompt`). The stepwise condition sends the same prompts without the harness.", ""]
    for level in ("one_line", "paragraph", "requirements"):
        task = rr.whole_task(level)
        parts += [f"### 5.{('one_line', 'paragraph', 'requirements').index(level) + 1}. {level} with the harness",
                  "", "Task file:", "", "```yaml\n" + yaml.safe_dump(task, sort_keys=False, allow_unicode=True)
                  + "```\n"]
        if "acceptanceCriteria" in task:
            parts += ["Prompt received by the agent:", "", block(build_prompt(task))]
        else:
            parts += ["The harness refuses this task when it is created (no acceptance criteria).", ""]
    parts += ["### 5.4. Super prompt with the harness, and stepwise without it: the 16 steps", ""]
    for step in rr.PROMPTS["steps"]:
        parts += [f"#### {step['id']}. {step['title']}", "", block(build_prompt(rr.step_task(step)))]
    from product_owner import PO_PROMPT  # noqa: PLC0415
    parts += ["## 6. Clarification with harness 1.1.0 (clarify condition)", "",
              "The paragraph task runs with `intake.criteriaPolicy: enforce`. INTENT asks questions about the "
              "criterion `It works.`; a separate agent call plays the product owner with the prompt below "
              "(`{task}` is the current task, `{questions}` the open questions, `{knowledge}` SPEC.md). Its "
              "answers go to `harness task clarify` as `human.product-owner-simulated`.", "", block(PO_PROMPT)]
    (HERE / "PROMPTS.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"PROMPTS.md: {sum(len(p.split()) for p in parts)} words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
