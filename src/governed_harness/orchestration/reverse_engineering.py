"""Reverse engineering of an existing project: persistent documents (wave 11, #97).

The architecture survey of an existing project (DISCOVERY, once per project) already infers the
style and the layer rules. Under ``architecture.documentation: project`` the same call also
describes the components, the organisation of files and folders, the conventions and how the
harness should act on the project, and the harness writes that as documents inside the project,
``.harness/reverse-engineering``:

* ``README.md``: the index, what each document is for and how to refresh them;
* ``structure.md``: the source directories (listed by the harness, not by the agent), the
  organisation the agent describes and the style;
* ``components.md``: the main components, where they live and what each one is responsible for;
* ``conventions.md``: the conventions the code shows (naming, tests, errors, configuration);
* ``working-agreement.md``: how the harness and its agents act on the project from then on.

Later requests carry a pointer to the directory and the working agreement, so an agent reads the
documents on demand instead of analysing the project again. The survey is reused while the
source layout holds (``architecture.survey.reused`` records each reuse with the digest of the
documents) and runs again only on ``harness architecture refresh`` (or ``refresh: auto`` and a
material change of the layout, or documents that are missing)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from governed_harness.evidence.hashing import sha256_bytes, sha256_json

DIRECTORY = "reverse-engineering"
INDEX = "README.md"
AGREEMENT = "working-agreement.md"
FILES = (INDEX, "structure.md", "components.md", "conventions.md", AGREEMENT)
_MAX_COMPONENTS = 40
_MAX_ITEMS = 30
_MAX_TEXT = 20_000
_MAX_AGREEMENT = 1500

SURVEY_SUFFIX = (
    " Besides the fields above the result needs the documentation of the project: "
    '"organization" (Markdown: how files and folders are organised and where new code goes), '
    '"components" (the main components: [{"name": "<name>", "path": "<path>", '
    '"responsibility": "<one sentence>"}]), "conventions" (the conventions the code shows: '
    'naming, tests, errors, configuration; a list of short sentences) and "guidance" (how an '
    "agent must act on this project from now on: where to put code, what to run, what not to "
    "touch; a list of short sentences). Base each on what you read; do not invent."
)
"""Added to the instructions of the survey under ``architecture.documentation: project``."""


def _texts(value: Any, name: str, limit: int) -> list[str]:
    if not isinstance(value, list):
        raise ValueError(f"the survey needs a '{name}' list")
    items = [str(item).strip()[:600] for item in value if str(item).strip()]
    return items[:limit]


def _component(item: Any) -> dict[str, str]:
    if not isinstance(item, dict):
        raise ValueError("a component is an object")
    fields = {key: str(item.get(key) or "").strip()[:400] for key in ("name", "path")}
    fields["responsibility"] = str(item.get("responsibility") or "").strip()[:600]
    if not fields["name"] or not fields["responsibility"]:
        raise ValueError("every component needs a name and a responsibility")
    if fields["path"].startswith("/") or ".." in fields["path"].split("/"):
        raise ValueError(f"component {fields['name']}: the path must be relative")
    return fields


def validate_documentation(result: dict[str, Any]) -> dict[str, Any]:
    """The documentation fields of a survey answer; a missing or empty part is an error, so a
    survey cannot pass as documentation with nothing in it (fail closed)."""
    organization = result.get("organization")
    if not isinstance(organization, str) or not organization.strip():
        raise ValueError("the survey needs an 'organization' text")
    raw = result.get("components")
    if not isinstance(raw, list) or not raw:
        raise ValueError("the survey needs a non-empty 'components' list")
    documentation = {
        "organization": organization.strip()[:_MAX_TEXT],
        "components": [_component(item) for item in raw[:_MAX_COMPONENTS]],
        "conventions": _texts(result.get("conventions"), "conventions", _MAX_ITEMS),
        "guidance": _texts(result.get("guidance"), "guidance", _MAX_ITEMS),
    }
    if not documentation["guidance"]:
        raise ValueError("the survey needs a non-empty 'guidance' list")
    return documentation


def _bullets(items: list[str]) -> list[str]:
    return [f"- {item}" for item in items] or ["- Nothing was recorded."]


def _render(
    survey: dict[str, Any], docs: dict[str, Any], layout: list[str], digest: str
) -> dict[str, str]:
    style = survey["style"]
    stamp = f"Generated by the harness from the survey `{digest}`. Do not edit by hand."
    components = [
        f"- `{item['path'] or '.'}` **{item['name']}**: {item['responsibility']}"
        for item in docs["components"]
    ]
    return {
        INDEX: "\n".join(
            [
                "# Reverse engineering of the project",
                "",
                stamp,
                "",
                *[f"- `{name}`" for name in FILES[1:]],
                "",
                "The harness did this analysis once. Agents read these documents instead of "
                "analysing the project again. To redo it after the project changed materially, "
                "run `harness architecture refresh`: the next run surveys the project again "
                "and rewrites them.",
            ]
        ),
        "structure.md": "\n".join(
            [
                f"# Structure ({style})",
                "",
                stamp,
                "",
                "## Source directories",
                "",
                *[f"- `{item}`" for item in layout],
                "",
                "## Organisation",
                "",
                docs["organization"],
                "",
                "## Architecture",
                "",
                survey["summary"],
            ]
        ),
        "components.md": "\n".join(["# Main components", "", stamp, "", *components]),
        "conventions.md": "\n".join(
            ["# Conventions", "", stamp, "", *_bullets(docs["conventions"])]
        ),
        AGREEMENT: "\n".join(
            [
                "# How the harness acts on this project",
                "",
                stamp,
                "",
                *_bullets(docs["guidance"]),
                "",
                "- Read these documents before searching the code; do not analyse the whole "
                "project again.",
                "- Respect the architecture rules the project approved; a change that needs "
                "another structure goes through a person.",
            ]
        ),
    }


def write_documents(
    harness_dir: Path,
    survey: dict[str, Any],
    docs: dict[str, Any],
    layout: list[str],
    *,
    digest: str,
) -> dict[str, Any]:
    """Write the documents; the record (digest of the set and of each file) goes in the state."""
    target = harness_dir / DIRECTORY
    target.mkdir(parents=True, exist_ok=True)
    rendered = _render(survey, docs, layout, digest)
    files: dict[str, str] = {}
    for name, text in rendered.items():
        body = text.rstrip() + "\n"
        (target / name).write_text(body, encoding="utf-8")
        files[name] = sha256_bytes(body.encode("utf-8"))
    return {"directory": f".harness/{DIRECTORY}", "files": files, "digest": sha256_json(files)}


def present(harness_dir: Path, record: Any) -> bool:
    """Whether the documents of ``record`` are all in the project."""
    if not isinstance(record, dict) or not isinstance(record.get("files"), dict):
        return False
    return all((harness_dir / DIRECTORY / name).is_file() for name in record["files"])


def request_block(harness_dir: Path, record: Any) -> dict[str, Any] | None:
    """What the requests carry: where the documents are and the working agreement (short)."""
    if not present(harness_dir, record):
        return None
    agreement = (harness_dir / DIRECTORY / AGREEMENT).read_text(encoding="utf-8")
    return {
        "directory": f".harness/{DIRECTORY}",
        "files": list(record["files"]),
        "digest": record["digest"],
        "workingAgreement": agreement[:_MAX_AGREEMENT],
    }


